// Generates shared/styles/mobile-type.css: smaller type on phones (<= 430px wide).
// It overrides only the base (unprefixed) text-[..] sizes, so sm:/md:/lg: sizes and desktop stay as they are.
// Run after adding new text sizes: npm run gen:type
import fs from "node:fs";
import path from "node:path";

const roots = ["landing/app", "landing/components", "webapp/app", "webapp/components", "shared/components"];
const files = [];
const walk = (d) => { for (const e of fs.readdirSync(d, { withFileTypes: true })) { const p = path.join(d, e.name); if (e.isDirectory()) walk(p); else if (/\.tsx?$/.test(e.name)) files.push(p); } };
roots.forEach((r) => fs.existsSync(r) && walk(r));

const px = new Set(), clamps = new Set();
for (const f of files) {
  const src = fs.readFileSync(f, "utf8");
  // a base class: not preceded by a variant colon or by "!"
  for (const m of src.matchAll(/(?<![:!\w-])text-\[([^\]\s]+)\]/g)) {
    const v = m[1];
    if (/^\d+(\.\d+)?px$/.test(v)) px.add(parseFloat(v));
    else if (/^clamp\(\d+(\.\d+)?(px|rem),/.test(v)) clamps.add(v);
  }
}
const esc = (s) => s.replace(/[^a-zA-Z0-9_-]/g, (c) => `\\${c}`);
const round = (n) => Math.round(n * 2) / 2;
/** phone scale per size: big display type shrinks most, small UI text stays */
const phone = (n) => (n >= 40 ? n * 0.8 : n >= 28 ? n * 0.86 : n >= 20 ? n * 0.91 : n >= 17 ? n * 0.95 : n >= 15 ? n - 0.5 : n);
const small = (n) => (n >= 40 ? n * 0.72 : n >= 28 ? n * 0.8 : phone(n)); // <= 370px (small Androids, iPhone SE/mini)

const rules = (fn) => {
  const out = [];
  for (const n of [...px].sort((a, b) => a - b)) { const to = round(fn(n)); if (to !== n) out.push(`  .${esc(`text-[${n}px]`)} { font-size: ${to}px; }`); }
  for (const c of [...clamps].sort()) {
    const [, num, unit] = c.match(/^clamp\((\d+(?:\.\d+)?)(px|rem),/);
    const min = unit === "rem" ? +num * 16 : +num;
    out.push(`  .${esc(`text-[${c}]`)} { font-size: ${round(fn(min))}px; }`);
  }
  return out.join("\n");
};
const css = `/* Generated by scripts/gen-mobile-type.mjs. Do not edit by hand: run \`npm run gen:type\`. */
/* Phones only. Unlayered, so it wins over Tailwind's utilities layer; desktop sizes are untouched. */
@media (max-width: 430px) {
${rules(phone)}
}
@media (max-width: 370px) {
${rules(small)}
}
`;
fs.writeFileSync("shared/styles/mobile-type.css", css);
console.log(`mobile-type.css: ${px.size} px sizes, ${clamps.size} clamp sizes`);
