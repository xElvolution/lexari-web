// Compiles src/lib/backgrounds.json (the web app's ID-card backgrounds) into Solidity,
// so the onchain NFT image uses exactly the same artwork. Run: node script/gen-backgrounds.mjs
import { readFileSync, writeFileSync } from "node:fs";
const bgs = JSON.parse(readFileSync(new URL("../../src/lib/backgrounds.json", import.meta.url)));
const lit = (s) => `"${s.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
const body = bgs.map((b, i) => {
  const parts = b.svg.split("{U}");
  const expr = parts.map((p, k) => (k ? `uid, ${lit(p)}` : lit(p))).join(", ");
  return `        if (i == ${i}) return string.concat(${expr});`;
}).join("\n");
const sol = `// SPDX-License-Identifier: MIT
// GENERATED by script/gen-backgrounds.mjs from src/lib/backgrounds.json. Do not edit by hand.
pragma solidity ^0.8.26;

/// @notice NFT-style ID card backgrounds (100x100 tiles), shared with the Lexari web app.
contract LexariBackgrounds {
    uint8 public constant COUNT = ${bgs.length};

    function name(uint8 i) external pure returns (string memory) {
${bgs.map((b, i) => `        if (i == ${i}) return ${lit(b.label)};`).join("\n")}
        return ${lit(bgs[0].label)};
    }

    /// @param uid prefix that keeps gradient / pattern ids unique inside one SVG
    function svg(uint8 i, string memory uid) external pure returns (string memory) {
${body}
        return ${lit(bgs[0].svg)};
    }
}
`;
writeFileSync(new URL("../src/LexariBackgrounds.sol", import.meta.url), sol);
console.log("wrote", bgs.length, "backgrounds");
