#!/usr/bin/env python3
"""Writes the mainnet webapp.env. New secrets are generated here; only network-neutral settings are copied from the
testnet env. Values are never printed. Usage: make-mainnet-env.py <testnet.env> <out.env> <db-password-file>"""
import base64, hashlib, os, secrets, sys
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives import serialization

src, out, pwfile = sys.argv[1:4]
t = {}
for line in open(src):
    line = line.rstrip("\n")
    if line and not line.startswith("#") and "=" in line:
        k, v = line.split("=", 1); t[k.strip()] = v

# Settings that are the same on both networks (LLM relay, rate limits, read-only data APIs). Never: SESSION_SECRET,
# DATABASE_URL, LEXARI_FAUCET_KEY, LEXARI_ATTESTOR_KEY, LEXARI_TREASURY, program id, USDC mint, Privy, desktop relay,
# VAPID or MODEL_KEYS_SECRET (those are network specific or get new values below).
SHARED_KEYS = ["NEXT_PUBLIC_LANDING_URL", "TRUST_PROXY", "CHAT_PER_MINUTE", "CHAT_PER_DAY", "LLM_PROVIDER", "GROK_CLI_BIN",
               "GROK_CLI_HOME", "GROK_CLI_CONCURRENCY", "GROK_CLI_SOCKET", "ZG_COMPUTE_API_KEY", "NANSEN_API_KEY",
               "NEXT_PUBLIC_NANSEN_READY", "AURORA_INTENTS_API_KEY", "NEXT_PUBLIC_INTENTS_READY", "AURORA_INTENTS_LIVE", "VAPID_SUBJECT"]

def b64u(b): return base64.urlsafe_b64encode(b).rstrip(b"=").decode()
k = ec.generate_private_key(ec.SECP256R1())
vapid_pub = b64u(k.public_key().public_bytes(serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint))
vapid_priv = b64u(k.private_numbers().private_value.to_bytes(32, "big"))
pw = open(pwfile).read().strip()
mainnet_rpc = t.get("SOLANA_MAINNET_RPC", "").strip()

env = [
    "# Lexari MAINNET (mainnet.lexari.ai). Generated by deploy/mainnet/make-mainnet-env.py. Mode 600, owner lexarimain.",
    "# Never copy LEXARI_FAUCET_KEY or the testnet SESSION_SECRET here.",
    "LEXARI_NETWORK=mainnet",
    "NEXT_PUBLIC_LEXARI_NETWORK=mainnet",
    "NEXT_PUBLIC_SOLANA_CLUSTER=mainnet-beta",
    "NEXT_PUBLIC_WEBAPP_URL=https://mainnet.lexari.ai",
    "LEXARI_APP_ORIGIN=https://mainnet.lexari.ai",
    f"DATABASE_URL=postgres://lexari_mainnet:{pw}@127.0.0.1:5433/lexari_mainnet",
    f"SESSION_SECRET={secrets.token_hex(48)}",
    f"MODEL_KEYS_SECRET={secrets.token_hex(32)}",
    f"VAPID_PUBLIC_KEY={vapid_pub}",
    f"VAPID_PRIVATE_KEY={vapid_priv}",
    "# Solana mainnet-beta: Circle USDC; RPC from the server's existing SOLANA_MAINNET_RPC (set HELIUS_API_KEY for a private one)",
    "NEXT_PUBLIC_USDC_MINT=EPjFWdd5AufqSSqeM2qN1xzybapC8G4wEGGkZwyTDt1v",
    f"SOLANA_RPC={mainnet_rpc}" if mainnet_rpc else "# SOLANA_RPC= (unset: public mainnet-beta endpoint)",
    f"NEXT_PUBLIC_SOLANA_RPC={mainnet_rpc}" if mainnet_rpc else "# NEXT_PUBLIC_SOLANA_RPC=",
    "# Guards: mainnet refuses to start with the testnet database or session secret (server/network.ts)",
    f"LEXARI_TESTNET_DATABASE_URL={t.get('DATABASE_URL', '')}",
    f"LEXARI_TESTNET_SESSION_SECRET_SHA256={hashlib.sha256(t.get('SESSION_SECRET', '').encode()).hexdigest() if t.get('SESSION_SECRET') else ''}",
    "# Real funds: sign tools (sends, x402) run on mainnet only with this flag, inside the $2/$10 default limits",
    "LEXARI_MAINNET_EXECUTION=1",
    "# Funding agents from the Lexari balance sends REAL USDC from LEXARI_PAYOUT_KEY: off until the owner funds that wallet",
    "LEXARI_MAINNET_FUNDING=",
    "# Launch cap for crypto top-ups credited per person per day (US dollars)",
    "MAINNET_TOPUP_DAILY_USD=100",
    "# Card payments: CARD_PROVIDER=stripe (STRIPE_SECRET_KEY sk_live_..., STRIPE_WEBHOOK_SECRET whsec_...) or",
    "# CARD_PROVIDER=paystack (PAYSTACK_SECRET_KEY sk_live_..., optional PAYSTACK_CURRENCY). Owner provides the keys.",
    "CARD_PROVIDER=",
    "# Owner provides (mainnet only): LEXARI_TREASURY / NEXT_PUBLIC_LEXARI_TREASURY (multisig address),",
    "# LEXARI_PAYOUT_KEY (funded fee payer / x402 facilitator), NEXT_PUBLIC_LEXARI_PROGRAM_ID + LEXARI_ATTESTOR_KEY",
    "# (after the program is deployed), NEXT_PUBLIC_PRIVY_APP_ID + PRIVY_APP_SECRET (own Privy app), HELIUS_API_KEY, ALCHEMY_API_KEY.",
    "# Copied from the testnet env (network-neutral settings only):",
]
for key in SHARED_KEYS:
    if key in t: env.append(f"{key}={t[key]}")
fd = os.open(out, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
with os.fdopen(fd, "w") as f: f.write("\n".join(env) + "\n")
print("wrote", out, "with", sum(1 for l in env if l and not l.startswith("#")), "settings")
